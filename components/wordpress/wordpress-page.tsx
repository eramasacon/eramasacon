import type { ReactNode } from "react";

/**
 * Astra page-builder template wrapper around an Elementor page, as WordPress
 * rendered it. The Elementor CSS for the page expects this markup.
 */
export function WordPressPage({ pageId, stylesheet, children }: { pageId: number; stylesheet: string; children: ReactNode }) {
  return (
    <div className="site-content" id="content">
      {/* Page-specific Elementor CSS, generated by scripts/wp-port/port_page.py. */}
      <link rel="stylesheet" href={stylesheet} precedence="wordpress-page" />
      <div className="ast-container">
        <div className="content-area primary" id="primary">
          <main className="site-main" id="main">
            <article className={`post-${pageId} page type-page status-publish ast-article-single`} id={`post-${pageId}`}>
              <header className="entry-header ast-no-thumbnail ast-no-title ast-header-without-markup" />
              <div className="entry-content clear">
                <div className={`elementor elementor-${pageId}`} data-elementor-type="wp-page" data-elementor-id={pageId}>
                  {children}
                </div>
              </div>
            </article>
          </main>
        </div>
      </div>
    </div>
  );
}
